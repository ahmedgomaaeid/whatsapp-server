#!/bin/bash

# إزالة ملف القفل الخاص بالشاشة إذا كان موجوداً (لتجنب الأخطاء عند إعادة التشغيل)
rm -f /tmp/.X99-lock

# تشغيل Xvfb (الشاشة الوهمية) بدقة 1920x1080
# :99 هو رقم الشاشة
Xvfb :99 -screen 0 1920x1080x24 &

# تصدير متغير الشاشة
export DISPLAY=:99

# انتظار ثواني لتجهيز الشاشة
sleep 2

# تشغيل التطبيق
exec python app.py